/** Display formatting only: fixed 2 decimals via decimal.js, then locale separators by string ops (no float math). */
export function formatAmount(v: string | undefined, lang: Lang, decimals = 2): string {
  if (v === undefined || v === "") return "";
  let d: Decimal;
  try {
    d = new Decimal(v);
  } catch {
    return esc(v);
  }
  const fixed = decimals >= 0 ? d.toFixed(decimals) : d.toString();
  const [int = "0", frac] = fixed.replace("-", "").split(".");
  const grouped = int.replace(/\B(?=(\d{3})+(?!\d))/g, lang === "de" ? "." : ",");
  const sep = lang === "de" ? "," : ".";
  return `${d.isNegative() ? "-" : ""}${grouped}${frac !== undefined ? sep + frac : ""}`;
}

